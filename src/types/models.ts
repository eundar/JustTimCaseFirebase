import type { CaseType, DocumentType } from "./types"

export interface AttorneyProfile {
  name: string
  specialization: string
  email: string
}

export interface Client {
  id: string
  ownerId: string
  name: string
  email: string
  phone: string
}

//added Opposing Party field to Case interface added a "?"
// to make it optional since not all cases will have an opposing party
export interface Case {
  id: string
  ownerId: string
  title: string
  clientId: string
  opposingParty?: string
  type: CaseType
  status: "Active" | "Pending" | "Closed"
  openDate: string
}

export interface Appointment {
  id: string
  ownerId: string
  clientId: string
  caseId: string | null
  type: string
  date: string
  time: string
  status: "Scheduled" | "Confirmed" | "Completed" | "Pending"
  location: string
}

export interface DocumentRecord {
  id: string
  ownerId: string
  name: string
  caseId: string
  clientId: string
  type: DocumentType
  uploadedDate: string
  size: string
  url: string
  storagePath: string
}

export interface ProspectiveClient {
  // Generated by the server
  id: string

  // Contact information
  fullName: string
  email: string
  phone: string

  // Legal matter information
  caseType: CaseType
  caseDescription: string
  opposingParty?: string
  privacyAgreementAccepted: boolean

  // Urgency and consultation
  // hasUpcomingDeadline: boolean;
  // consultationRequested: boolean;

  // Intake workflow
  status: "Pending Review" | "Accepted" | "Declined"
  createdAt: string
}
